/**
 * Generates src/lib/states.ts from us-atlas's pre-projected AlbersUSA
 * topology (975x610, Alaska and Hawaii inset). Run: npm run build:states
 */
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoPath } from "d3-geo";
import type { Topology, GeometryCollection } from "topojson-specification";
import type { Feature, Geometry } from "geojson";

const FIPS: Record<string, [string, string]> = {
  "01": ["AL", "Alabama"], "02": ["AK", "Alaska"], "04": ["AZ", "Arizona"],
  "05": ["AR", "Arkansas"], "06": ["CA", "California"], "08": ["CO", "Colorado"],
  "09": ["CT", "Connecticut"], "10": ["DE", "Delaware"], "11": ["DC", "District of Columbia"],
  "12": ["FL", "Florida"], "13": ["GA", "Georgia"], "15": ["HI", "Hawaii"],
  "16": ["ID", "Idaho"], "17": ["IL", "Illinois"], "18": ["IN", "Indiana"],
  "19": ["IA", "Iowa"], "20": ["KS", "Kansas"], "21": ["KY", "Kentucky"],
  "22": ["LA", "Louisiana"], "23": ["ME", "Maine"], "24": ["MD", "Maryland"],
  "25": ["MA", "Massachusetts"], "26": ["MI", "Michigan"], "27": ["MN", "Minnesota"],
  "28": ["MS", "Mississippi"], "29": ["MO", "Missouri"], "30": ["MT", "Montana"],
  "31": ["NE", "Nebraska"], "32": ["NV", "Nevada"], "33": ["NH", "New Hampshire"],
  "34": ["NJ", "New Jersey"], "35": ["NM", "New Mexico"], "36": ["NY", "New York"],
  "37": ["NC", "North Carolina"], "38": ["ND", "North Dakota"], "39": ["OH", "Ohio"],
  "40": ["OK", "Oklahoma"], "41": ["OR", "Oregon"], "42": ["PA", "Pennsylvania"],
  "44": ["RI", "Rhode Island"], "45": ["SC", "South Carolina"], "46": ["SD", "South Dakota"],
  "47": ["TN", "Tennessee"], "48": ["TX", "Texas"], "49": ["UT", "Utah"],
  "50": ["VT", "Vermont"], "51": ["VA", "Virginia"], "53": ["WA", "Washington"],
  "54": ["WV", "West Virginia"], "55": ["WI", "Wisconsin"], "56": ["WY", "Wyoming"],
};

const topo = JSON.parse(
  readFileSync("node_modules/us-atlas/states-albers-10m.json", "utf8"),
) as Topology<{ states: GeometryCollection }>;

const fc = feature(topo, topo.objects.states);
const path = geoPath(); // null projection: coordinates are already in px
const round = (n: number) => Math.round(n * 10) / 10;

const states = fc.features
  .map((f: Feature<Geometry>) => {
    const id = String(f.id).padStart(2, "0");
    const meta = FIPS[id];
    if (!meta) return null;
    const [abbr, name] = meta;
    const d = path(f);
    const [cx, cy] = path.centroid(f);
    const [[x0, y0], [x1, y1]] = path.bounds(f);
    if (!d) return null;
    return {
      abbr, name, fips: id, d,
      cx: round(cx), cy: round(cy),
      bbox: [round(x0), round(y0), round(x1), round(y1)] as [number, number, number, number],
    };
  })
  .filter((s): s is NonNullable<typeof s> => s !== null)
  .sort((a, b) => a.name.localeCompare(b.name));

const seen = new Set(states.map((s) => s.abbr));
const missing = Object.values(FIPS).map(([a]) => a).filter((a) => !seen.has(a));
if (missing.length) throw new Error(`Missing states: ${missing.join(", ")}`);

const out = `// GENERATED by scripts/build-states.ts from us-atlas states-albers-10m.json.
// Do not edit by hand. ViewBox is 0 0 975 610 (AlbersUSA, AK/HI inset).

export const VIEW_W = 975;
export const VIEW_H = 610;

export type StateShape = {
  abbr: string;
  name: string;
  fips: string;
  /** SVG path data, pre-projected */
  d: string;
  /** centroid in viewBox px */
  cx: number;
  cy: number;
  /** [x0, y0, x1, y1] in viewBox px */
  bbox: [number, number, number, number];
};

export const STATES: readonly StateShape[] = ${JSON.stringify(states, null, 2)} as const;

export const STATE_BY_ABBR: Readonly<Record<string, StateShape>> = Object.fromEntries(
  STATES.map((s) => [s.abbr, s]),
);

export const STATE_ABBRS: readonly string[] = STATES.map((s) => s.abbr);
`;

writeFileSync("src/lib/states.ts", out);
console.log(`wrote ${states.length} states to src/lib/states.ts`);
